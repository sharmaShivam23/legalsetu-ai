// ==========================================================
// LegalSetu — Rights Clock: BNS punishment table + lookup
// ----------------------------------------------------------
// The table itself (bns-punishments.json) is generated from the
// Act text by scripts/build-bns-punishments.ts — see that file.
// This module only builds and reads it.
// ==========================================================

import { createHash } from "crypto";
import { parseAct, type PunishmentProfile } from "./punishment-parser";

export const EXCERPT_LIMIT = 320;

export interface TableEntry {
  title: string;
  punishment: PunishmentProfile | null;
  subsections: Record<string, PunishmentProfile | null>;
}

export interface PunishmentTable {
  act: "BNS";
  actName: string;
  source: string;
  /** First 16 hex chars of the source text's SHA-256 — ties the table to one exact text. */
  sourceHash: string;
  sections: Record<string, TableEntry>;
}

function trimExcerpt(p: PunishmentProfile | null): PunishmentProfile | null {
  if (!p) return null;
  const e = p.excerpt.length > EXCERPT_LIMIT ? p.excerpt.slice(0, EXCERPT_LIMIT - 1).trimEnd() + "…" : p.excerpt;
  return { ...p, excerpt: e };
}

export function hashSource(text: string): string {
  return createHash("sha256").update(text).digest("hex").slice(0, 16);
}

export function buildPunishmentTable(actText: string, sourcePath: string): PunishmentTable {
  const sections: Record<string, TableEntry> = {};
  for (const s of parseAct(actText)) {
    const subs: Record<string, PunishmentProfile | null> = {};
    for (const sub of s.subsections) if (sub.sub) subs[sub.sub] = trimExcerpt(sub.punishment);
    sections[s.section] = { title: s.title, punishment: trimExcerpt(s.punishment), subsections: subs };
  }
  return {
    act: "BNS",
    actName: "Bharatiya Nyaya Sanhita, 2023",
    source: sourcePath,
    sourceHash: hashSource(actText),
    sections,
  };
}

/** Renders the table as the committed TypeScript module (see scripts/build-bns-punishments.ts). */
export function serializeTableModule(table: PunishmentTable): string {
  const json = JSON.stringify(table, null, 1);
  // The JSON sits inside a String.raw template literal; these two
  // sequences are the only ones that could break out of it.
  if (json.includes("`") || json.includes("${")) {
    throw new Error("Punishment table contains a backtick or ${ — cannot embed safely.");
  }
  return [
    "// ==========================================================",
    "// GENERATED by scripts/build-bns-punishments.ts — DO NOT EDIT.",
    `// Source: ${table.source} (sha256 ${table.sourceHash}…)`,
    "// Regenerate with: npm run rights-clock:build",
    "// ==========================================================",
    "",
    'import type { PunishmentTable } from "./punishment-table";',
    "",
    `export const BNS_PUNISHMENT_TABLE_JSON = String.raw\`${json}\`;`,
    "",
    "export const BNS_PUNISHMENT_TABLE: PunishmentTable = JSON.parse(BNS_PUNISHMENT_TABLE_JSON);",
    "",
  ].join("\n");
}

// ---------- Lookup ----------

export interface SectionRef {
  section: string;
  sub?: string;
  /** What the user typed, for error messages. */
  raw: string;
}

/**
 * Accepts the ways people actually write a charge: "303(2)", "303 (2)",
 * "BNS 303(2)", "s. 318(4)", "u/s 115", "Section 64(1)", "303/2".
 * Returns null for anything that is not a recognisable BNS reference.
 */
export function parseSectionRef(raw: string): SectionRef | null {
  const cleaned = raw
    .trim()
    .replace(/^(?:bns|b\.n\.s\.?)\s*/i, "")
    .replace(/^(?:u\/s|sec(?:tion)?\.?|s\.)\s*/i, "")
    .replace(/^(?:bns|b\.n\.s\.?)\s*/i, "")
    .trim();
  const m = cleaned.match(/^0*(\d{1,3})\s*(?:\(\s*(\d{1,2})\s*\)|\/\s*(\d{1,2}))?(?:\s*\(\s*[a-z]{1,4}\s*\))?$/i);
  if (!m) return null;
  const section = String(Number(m[1]));
  const sub = m[2] ?? m[3];
  return { section, sub: sub ? String(Number(sub)) : undefined, raw: raw.trim() };
}

export type LookupStatus =
  | "OK"
  /** Sub-section not given; the gravest sub-section was used. */
  | "SECTION_LEVEL"
  | "NOT_FOUND"
  /** Section exists but prescribes no punishment of its own (a definition). */
  | "NO_PUNISHMENT"
  /** Punishment defined by reference to another offence. */
  | "UNRESOLVABLE";

export interface LookupResult {
  ref: SectionRef;
  status: LookupStatus;
  title?: string;
  punishment?: PunishmentProfile;
  /** Human-readable citation, e.g. "BNS §303(2)". */
  citation: string;
}

export function lookupSection(table: PunishmentTable, ref: SectionRef): LookupResult {
  const entry = table.sections[ref.section];
  const citation = `BNS §${ref.section}${ref.sub ? `(${ref.sub})` : ""}`;
  if (!entry) return { ref, status: "NOT_FOUND", citation };

  let profile: PunishmentProfile | null;
  let status: LookupStatus = "OK";
  if (ref.sub) {
    if (!(ref.sub in entry.subsections)) return { ref, status: "NOT_FOUND", title: entry.title, citation };
    profile = entry.subsections[ref.sub];
  } else {
    profile = entry.punishment;
    if (Object.keys(entry.subsections).length > 1) status = "SECTION_LEVEL";
  }

  if (!profile) return { ref, status: "NO_PUNISHMENT", title: entry.title, citation };
  if (!profile.resolvable) return { ref, status: "UNRESOLVABLE", title: entry.title, punishment: profile, citation };
  return { ref, status, title: entry.title, punishment: profile, citation };
}
