const SETS: Record<string, PhraseSet> = { en, hi, ta, te, bn, mr, gu, kn, ml, pa };

/**
 * Languages without their own set borrow the closest one the caller can
 * follow: Maithili and Bhojpuri speakers understand Hindi, Assamese
 * speakers understand Bengali. Anything else falls back to English.
 */
const BORROW: Record<string, string> = { mai: "hi", bho: "hi", sat: "hi", as: "bn", or: "hi", ur: "hi" };

export function phrasesFor(language: string): PhraseSet {
  const base = language.split("-")[0].toLowerCase();
  return SETS[base] ?? SETS[BORROW[base] ?? "en"];
}

/** The language code whose phrases `phrasesFor` actually returns. */
export function phraseLanguage(language: string): string {
  const base = language.split("-")[0].toLowerCase();
  return SETS[base] ? base : (BORROW[base] ?? "en");
}
