// ==========================================================
// LegalSetu — fixed spoken phrases for phone calls
// ----------------------------------------------------------
// Everything the assistant says that does NOT come from the AI: the
// opening disclosure, acknowledgements, prompts, the safety message.
// They are fixed text, so they are synthesised once and cached on disk
// (see lib/calls/speech.ts) — a repeat call plays them instantly.
//
// English and Hindi were written carefully. The other languages are
// short, plain phrasings written for this project and have not been
// reviewed by a native speaker; have one read them before a public launch.
// ==========================================================

export interface PhraseSet {
  /** Opening: who we are, that this is not a lawyer, that it is saved, then the first question. */
  greeting: string;
  /** Played if the answer is slow, to show the call is alive. */
  acks: string[];
  /** Nothing intelligible was heard. */
  retry: string;
  /** The caller has gone quiet. */
  silence: string;
  goodbye: string;
  /** Immediate-danger safety message. */
  emergency: string;
  timeLimit: string;
  techError: string;
  /** Said when a long answer is cut short on the phone: the rest is in the history. */
  fullSaved: string;
}

