// ==========================================================
// LegalSetu — voice mode end to end, in a real browser
// ----------------------------------------------------------
//   npm run dev                                           # another terminal
//   node scripts/voice-local-e2e.mjs [seconds]            # Ollama mode
//   node scripts/voice-local-e2e.mjs [seconds] --cloud    # API-key mode
//
// --cloud switches Ollama mode OFF and checks the production path instead:
// Sarvam / Groq Whisper hear, the cloud model answers, and the reply is
// spoken by Sarvam if it has credit, otherwise by the browser's voice.
// Either way the toggle is put back the way it was found.
//
// A fake microphone asks a question in Hindi, waits, then asks one in
// English. Ollama mode is switched ON through the same API the toggle
// uses. Passes only when, with NO cloud speech service involved:
//   - every utterance is transcribed by local Whisper,
//   - every answer is generated by Ollama,
//   - every answer is spoken, in the language that was spoken,
//   - no control marker reaches the screen or the voice.
//
// The browser's speech synthesiser is replaced by a recorder (headless
// Chromium has no voices), so the test sees exactly what would be spoken
// and with which voice. Everything else is the real app.
// The questions come from .cache/call-sim (recorded speech) — no TTS API.
// ==========================================================

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { chromium } from "@playwright/test";
import { PrismaClient } from "@prisma/client";
import bcrypt from "bcryptjs";

const BASE = "http://localhost:3000";
const EMAIL = "voice-local-e2e@legalsetu.local";
const PASSWORD = "VoiceLocal!2026";
const CLOUD = process.argv.includes("--cloud");
const RUN_SECONDS = Number(process.argv.slice(2).find((a) => /^\d+$/.test(a)) ?? (CLOUD ? 120 : 240));
// Silence after each question: room to answer (a laptop CPU needs far more).
const GAP_SECONDS = CLOUD ? 30 : 75;

// --- fake mic: Hindi question, silence, English question, silence -------
const simDir = path.join(process.cwd(), ".cache", "call-sim");
const pick = (prefix) => {
  const f = fs.readdirSync(simDir).find((n) => n.startsWith(prefix));
  if (!f) throw new Error(`no ${prefix}* clip in .cache/call-sim`);
  return path.join(simDir, f);
};
const HI = pick("hi-e0a4aee0a587"); // "मेरे मकान मालिक ने मेरा सिक्योरिटी डिपॉजिट वापस नहीं किया…"
const EN = pick("en-4d79"); // "My landlord has not returned my security deposit…"
const wavPath = path.join(os.tmpdir(), "legalsetu-fake-mic-local.wav");
execFileSync("ffmpeg", [
  "-loglevel", "error", "-y",
  "-f", "mulaw", "-ar", "8000", "-ac", "1", "-i", HI,
  "-f", "mulaw", "-ar", "8000", "-ac", "1", "-i", EN,
  "-filter_complex",
  // No gain: the recordings already peak near 0 dB, and boosting them
  // clipped the audio badly enough to make Whisper hallucinate.
  `[0]aresample=16000,apad=pad_dur=${GAP_SECONDS}[a];[1]aresample=16000,apad=pad_dur=${GAP_SECONDS}[b];[a][b]concat=n=2:v=0:a=1`,
  "-ar", "16000", "-ac", "1", "-c:a", "pcm_s16le", wavPath,
]);
console.log(`fake mic: Hindi question + ${GAP_SECONDS}s, English question + ${GAP_SECONDS}s\n`);

// --- user + browser -----------------------------------------------------
const prisma = new PrismaClient();
await prisma.user.upsert({
  where: { email: EMAIL },
  update: { passwordHash: await bcrypt.hash(PASSWORD, 10), emailVerified: new Date() },
  create: { email: EMAIL, name: "Voice Local", passwordHash: await bcrypt.hash(PASSWORD, 10), emailVerified: new Date() },
});

const browser = await chromium.launch({
  args: [
    "--use-fake-ui-for-media-stream",
    "--use-fake-device-for-media-stream",
    `--use-file-for-fake-audio-capture=${wavPath}`,
    "--autoplay-policy=no-user-gesture-required",
  ],
});
const ctx = await browser.newContext({ permissions: ["microphone"] });

// Recording speech synthesiser: two realistic voices, speaks at ~14 chars/s.
await ctx.addInitScript(() => {
  window.__spoken = [];
  const voices = [
    { name: "Google हिन्दी", lang: "hi-IN", localService: false, default: false, voiceURI: "g-hi" },
    { name: "Microsoft Heera - English (India)", lang: "en-IN", localService: true, default: true, voiceURI: "ms-heera" },
    { name: "Microsoft David - English (United States)", lang: "en-US", localService: true, default: false, voiceURI: "ms-david" },
  ];
  class FakeUtterance {
    constructor(text) { this.text = text; this.lang = ""; this.voice = null; this.rate = 1; this.pitch = 1; this.onend = null; this.onerror = null; }
  }
  let timers = [];
  const synth = {
    speaking: false,
    getVoices: () => voices,
    addEventListener() {}, removeEventListener() {},
    speak(u) {
      window.__spoken.push({ t: Date.now(), text: u.text, lang: u.lang, voice: u.voice?.name ?? null });
      synth.speaking = true;
      timers.push(setTimeout(() => { synth.speaking = false; u.onend?.(); }, 300 + u.text.length * 70));
    },
    cancel() { timers.forEach(clearTimeout); timers = []; synth.speaking = false; },
    pause() {}, resume() {},
  };
  Object.defineProperty(window, "speechSynthesis", { value: synth, configurable: true });
  window.SpeechSynthesisUtterance = FakeUtterance;

  // Cloud voice clips (Sarvam) play through <audio>; record those as well.
  window.__plays = [];
  const play = HTMLMediaElement.prototype.play;
  HTMLMediaElement.prototype.play = function (...a) {
    const e = { t: Date.now(), src: (this.src || "").slice(0, 5), state: "called" };
    window.__plays.push(e);
    const pr = play.apply(this, a);
    pr?.then?.(() => (e.state = "playing"), (err) => (e.state = "rejected:" + err?.name));
    return pr;
  };
});

const page = await ctx.newPage();
const t0 = Date.now();
const secs = () => ((Date.now() - t0) / 1000).toFixed(1);
const stamp = () => `t+${secs().padStart(5)}s`;
const net = [];
const reqAt = new Map();
page.on("request", (req) => { if (/\/api\/(voice|chat)\//.test(req.url())) reqAt.set(req, Date.now()); });
page.on("response", async (res) => {
  const u = res.url();
  if (!/\/api\/(voice|chat|ai)\//.test(u)) return;
  const took = reqAt.has(res.request()) ? Date.now() - reqAt.get(res.request()) : null;
  const rec = { at: stamp(), url: u.replace(BASE, "").split("?")[0], status: res.status(), took };
  if (u.includes("/api/voice/stt")) {
    try { const j = await res.json(); rec.note = j?.data?.transcript ?? j?.error?.message; rec.lang = j?.data?.languageCode; } catch {}
  }
  net.push(rec);
  console.log(`  ${rec.at}  ${rec.status} ${rec.url}${took != null ? ` (${(took / 1000).toFixed(1)}s headers)` : ""}${rec.note ? `  [${rec.lang}] "${rec.note}"` : ""}`);
});
// Every external host the page talks to — must be none for speech.
const external = new Set();
page.on("request", (req) => { const h = new URL(req.url()).host; if (!h.startsWith("localhost")) external.add(h); });
page.on("console", (m) => { if (m.type() === "error") console.log(`  [console] ${m.text().slice(0, 160)}`); });
page.on("pageerror", (e) => console.log(`  [pageerror] ${String(e).slice(0, 170)}`));

// --- sign in ----------------------------------------------------------
const jar = new Map();
const grab = (res) => { for (const c of res.headers.getSetCookie?.() ?? []) { const [p] = String(c).split(";"); const i = p.indexOf("="); if (i > 0) jar.set(p.slice(0, i).trim(), p.slice(i + 1).trim()); } };
const hdr = () => [...jar].map(([k, v]) => `${k}=${v}`).join("; ");
const csrfRes = await fetch(`${BASE}/api/auth/csrf`); grab(csrfRes);
const { csrfToken } = await csrfRes.json();
grab(await fetch(`${BASE}/api/auth/callback/credentials`, { method: "POST", redirect: "manual", headers: { "Content-Type": "application/x-www-form-urlencoded", Cookie: hdr() }, body: new URLSearchParams({ csrfToken, email: EMAIL, password: PASSWORD, redirect: "false" }) }));
await ctx.addCookies([...jar].map(([name, value]) => ({ name, value, domain: "localhost", path: "/" })));
await ctx.addCookies([{ name: "ls_lang", value: "en", domain: "localhost", path: "/" }]);

// --- Ollama mode ON (or OFF with --cloud), exactly what the toggle does --
const modeBefore = await (await fetch(`${BASE}/api/ai/mode`, { headers: { Cookie: hdr() } })).json();
const on = await (await fetch(`${BASE}/api/ai/mode`, { method: "POST", headers: { "Content-Type": "application/json", Cookie: hdr() }, body: JSON.stringify(CLOUD ? { enabled: false } : { enabled: true, model: process.env.E2E_OLLAMA_MODEL || "gemma3:1b" }) })).json();
const modeOk = CLOUD ? on?.data?.ollamaMode === false : on?.data?.ollamaMode === true;
console.log(CLOUD ? `API-key mode: ${modeOk ? "ON (Ollama OFF)" : "FAILED"}\n` : `Ollama mode: ${modeOk ? "ON" : "FAILED"} — model ${on?.data?.activeModel ?? on?.error?.message}\n`);
if (!modeOk) { await browser.close(); process.exit(1); }

// Anything failing from here on must still reach the restore at the end:
// a crash here once left the user's Ollama toggle switched off.
let runError = null;
try {
await page.goto(`${BASE}/dashboard/chat`, { waitUntil: "networkidle" });
const quick = page.getByRole("button", { name: /quick/i }).first();
if (await quick.count()) await quick.click().catch(() => {});
await page.locator('button:has(svg.lucide-audio-lines):visible').first().click();
console.log(`${stamp()}  voice mode opened\n`);

let lastPhase = "";
let completedTurns = 0;
while (Date.now() - t0 < RUN_SECONDS * 1000) {
  await page.waitForTimeout(400);
  const phase = (await page.locator('[role=dialog] [aria-live="polite"] p').first().innerText().catch(() => "")).trim();
  if (phase && phase !== lastPhase) { console.log(`  ${stamp()}  phase: ${phase}`); lastPhase = phase; }
  const errorShown = await page.getByText("Voice mode unavailable").count();
  if (errorShown) { console.log(`  ${stamp()}  ERROR: ${await page.locator("[role=dialog]").innerText()}`); break; }
  completedTurns = net.filter((r) => r.url === "/api/chat/stream" && r.status === 200).length;
  const spokenNow = await page.evaluate(() => window.__spoken.length + window.__plays.filter((p) => p.src === "blob:").length);
  if (completedTurns >= 2 && lastPhase.startsWith("Listening") && spokenNow > 0) break;
}
} catch (err) {
  runError = err;
  console.log(`\nRUN ERROR: ${String(err?.message ?? err).split("\n")[0]}`);
}

const spoken = await page.evaluate(() => window.__spoken);
const plays = await page.evaluate(() => window.__plays.filter((p) => p.src === "blob:"));
const status = net.find((r) => r.url === "/api/voice/status");
const badge = await page.getByText(/Ollama mode: running on this computer/).count();
const transcript = await page.locator("[role=dialog]").innerText().catch(() => "");

// --- verdict -------------------------------------------------------------
const stt = net.filter((r) => r.url === "/api/voice/stt");
const chats = net.filter((r) => r.url === "/api/chat/stream");
const speaks = net.filter((r) => r.url === "/api/voice/speak");
const devanagari = /[ऀ-ॿ]/;

console.log(`\nSTT calls: ${stt.length} (${stt.filter((r) => r.status !== 200).length} failed)`);
for (const r of stt) console.log(`  ${(r.took / 1000).toFixed(1)}s  [${r.lang}] ${r.note}`);
console.log(`chat turns: ${chats.length} (${chats.filter((r) => r.status !== 200).length} failed)`);
console.log(`server TTS requests: ${speaks.length} (${speaks.filter((r) => r.status === 200).length} ok)${CLOUD ? "" : " — expected 0: no local Piper voice, so the browser speaks"}`);
console.log(`cloud voice clips played: ${plays.filter((p) => p.state === "playing").length}`);
console.log(`clauses spoken by the browser: ${spoken.length}`);
for (const s of spoken.slice(0, 12)) console.log(`  +${((s.t - t0) / 1000).toFixed(1)}s [${s.voice}] ${s.text.slice(0, 80)}`);
console.log(`local-mode badge shown: ${badge > 0}`);

// Latency per turn: end of speech (STT request sent) -> first spoken word.
const sttReqs = net.filter((r) => r.url === "/api/voice/stt" && r.status === 200 && r.note);
for (const r of sttReqs) {
  const sent = Number(r.at.replace(/[^0-9.]/g, "")) - r.took / 1000;
  const first = [...spoken, ...plays].sort((a, b) => a.t - b.t).find((s) => (s.t - t0) / 1000 > sent);
  if (first) {
    console.log(`  turn "${r.note.slice(0, 40)}": transcribed in ${(r.took / 1000).toFixed(1)}s, first word spoken ${((first.t - t0) / 1000 - sent).toFixed(1)}s after the user stopped`);
  }
}
console.log(`external hosts contacted: ${[...external].join(", ") || "none"}`);

const hiTurn = stt.find((r) => r.lang === "hi-IN");
const enTurn = stt.find((r) => r.lang === "en-IN");
const spokeHindi = spoken.some((s) => devanagari.test(s.text) && s.voice === "Google हिन्दी");
const spokeEnglish = spoken.some((s) => !devanagari.test(s.text) && /Heera/.test(s.voice ?? ""));
const audioPlayed = plays.some((p) => p.state === "playing");
// Every clause must be read by a voice that can pronounce its script: the
// bug this guards is an English voice reading a Hindi reply as noise.
const mismatched = spoken.filter((s) => devanagari.test(s.text) !== (s.voice === "Google हिन्दी"));
for (const m of mismatched) console.log(`  VOICE MISMATCH [${m.voice}] ${m.text.slice(0, 60)}`);
// After EVERY English question — including one asked after Hindi turns in
// the same conversation — the first spoken clause must be English.
const secondsOf = (r) => Number(r.at.replace(/[^0-9.]/g, ""));
const englishTurnsAnsweredInHindi = stt
  .filter((r) => r.lang === "en-IN")
  .filter((r) => {
    const reply = spoken.find((s) => (s.t - t0) / 1000 > secondsOf(r));
    return reply && devanagari.test(reply.text);
  });
for (const r of englishTurnsAnsweredInHindi) console.log(`  ENGLISH QUESTION ANSWERED IN HINDI at ${r.at}`);
const leaked = /@@|<\|/.test(transcript) || spoken.some((s) => /@@|<\|/.test(s.text));
const cloudSpeech = [...external].some((h) => /sarvam|groq/i.test(h));

// Cloud mode: the reply is spoken by Sarvam (<audio>) when it has credit,
// otherwise by the browser — and then WITHOUT a failing request per clause.
const failedSpeaks = speaks.filter((r) => r.status !== 200).length;
const pageCrashed = Boolean(runError);
const checks = CLOUD
  ? {
      "Hindi question transcribed": Boolean(hiTurn),
      "English question transcribed": Boolean(enTurn),
      "every transcription succeeded": stt.every((r) => r.status === 200),
      "two answers streamed from the cloud model": chats.filter((r) => r.status === 200).length >= 2,
      "replies spoken (cloud voice or browser)": audioPlayed || (spokeHindi && spokeEnglish),
      "Hindi reply spoken in Hindi": audioPlayed || spokeHindi,
      "English reply spoken in English": audioPlayed || spokeEnglish,
      "no failing TTS request per clause": failedSpeaks <= 1,
      "every clause read by a voice matching its script": audioPlayed || mismatched.length === 0,
      "English questions answered in English": englishTurnsAnsweredInHindi.length === 0,
      "no markers leaked": !leaked,
      "no local-mode badge": badge === 0,
    }
  : {
      "Hindi question transcribed locally": Boolean(hiTurn),
      "English question transcribed locally": Boolean(enTurn),
      "two answers streamed from Ollama": chats.filter((r) => r.status === 200).length >= 2,
      "Hindi reply spoken with a Hindi voice": spokeHindi,
      "English reply spoken with an English voice": spokeEnglish,
      "no server TTS round-trips": speaks.length === 0,
      "every clause read by a voice matching its script": mismatched.length === 0,
      "no cloud speech service contacted": !cloudSpeech,
      "no markers leaked": !leaked,
      "local-mode badge shown": badge > 0,
    };
console.log("");
for (const [k, v] of Object.entries(checks)) console.log(`${v ? "  ok  " : " FAIL "} ${k}`);
const ok = !pageCrashed && Object.values(checks).every(Boolean);
console.log(ok ? (CLOUD ? "\nPASS — voice mode works end to end on the API-key path." : "\nPASS — voice mode works end to end on Ollama, with no API key.") : "\nFAIL");

// --- restore ---------------------------------------------------------------
if (Boolean(modeBefore?.data?.ollamaMode) !== !CLOUD) {
  await fetch(`${BASE}/api/ai/mode`, { method: "POST", headers: { "Content-Type": "application/json", Cookie: hdr() }, body: JSON.stringify({ enabled: Boolean(modeBefore?.data?.ollamaMode) }) });
}
await browser.close();
const user = await prisma.user.findUnique({ where: { email: EMAIL }, select: { id: true } }).catch(() => {
  console.log(`(cleanup skipped: database unreachable — delete ${EMAIL} later)`);
  return null;
});
if (user) {
  await prisma.message.deleteMany({ where: { conversation: { userId: user.id } } }).catch(() => {});
  await prisma.conversation.deleteMany({ where: { userId: user.id } }).catch(() => {});
  await prisma.user.delete({ where: { id: user.id } }).catch(() => {});
}
await prisma.$disconnect();
process.exit(ok ? 0 : 1);
